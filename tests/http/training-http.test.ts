import { randomUUID } from "node:crypto";
import { createServerClient } from "@supabase/ssr";
import { afterAll, beforeAll, describe, expect, it } from "vitest";
import type { AccountUser } from "@/contracts/auth";
import type { ChallengePreviewListResponse } from "@/contracts/challenge";
import type {
  CreateSessionResponse,
  SessionHistoryResponse,
  SessionMutationResponse,
  SessionSnapshot,
} from "@/contracts/session";
import {
  assertLocalTestTarget,
  getLocalTestConfig,
} from "../integration/helpers/local-supabase";
import {
  cleanupTestUsers,
  createVerifiedTestUser,
  type TestUser,
} from "../integration/helpers/test-users";

function appOrigin() {
  return assertLocalTestTarget(process.env.SUPABASE_TEST_APP_URL ?? "", "3000")
    .origin;
}

/** Real SSR-format cookies, generated by the supported provider adapter. */
async function loginBrowser(user: TestUser) {
  const config = getLocalTestConfig();
  const jar = new Map<string, string>();
  const client = createServerClient(config.url, config.publishableKey, {
    cookies: {
      getAll: () => [...jar].map(([name, value]) => ({ name, value })),
      setAll: (cookies) => {
        for (const { name, value } of cookies) {
          if (value) jar.set(name, value);
          else jar.delete(name);
        }
      },
    },
  });
  const login = await client.auth.signInWithPassword({
    email: user.email,
    password: user.password,
  });
  if (login.error)
    throw new Error("Could not establish local SSR test cookies.");
  expect(jar.size).toBeGreaterThan(0);
  return { client, jar };
}
type Browser = Awaited<ReturnType<typeof loginBrowser>>;

async function api<T = unknown>(
  browser: Browser | null,
  path: string,
  body?: unknown,
  extraHeaders: Record<string, string> = {},
) {
  const origin = appOrigin();
  const headers = new Headers(extraHeaders);
  if (browser)
    headers.set(
      "Cookie",
      [...browser.jar].map(([name, value]) => `${name}=${value}`).join("; "),
    );
  if (body !== undefined) {
    if (!headers.has("Origin")) headers.set("Origin", origin);
    if (!headers.has("Content-Type"))
      headers.set("Content-Type", "application/json");
  }
  const response = await fetch(`${origin}${path}`, {
    method: body === undefined ? "GET" : "POST",
    headers,
    body: body === undefined ? undefined : JSON.stringify(body),
    redirect: "manual",
  });
  // Preserve refresh/chunk deletion exactly as a browser would between requests.
  if (browser)
    for (const header of response.headers.getSetCookie()) {
      const pair = header.split(";", 1)[0];
      const split = pair.indexOf("=");
      const name = pair.slice(0, split),
        value = pair.slice(split + 1);
      if (value && !/max-age=0(?:;|$)/i.test(header))
        browser.jar.set(name, value);
      else browser.jar.delete(name);
    }
  const text = await response.text();
  let data: unknown;
  try {
    data = JSON.parse(text);
  } catch {
    throw new Error(
      `Expected JSON from ${path}, received HTTP ${response.status}.`,
    );
  }
  expect(response.headers.get("cache-control")).toContain("private");
  expect(response.headers.get("cache-control")).toContain("no-store");
  return { response, data: data as T };
}

function savedCommand(session: SessionSnapshot) {
  const item = session.items[session.currentIndex!];
  return {
    item,
    body: {
      optionId: item.challenge.options[0].id,
      requestId: randomUUID(),
      expectedRevision: session.revision,
    },
  };
}

describe("real Next.js HTTP routes with Supabase SSR cookies", () => {
  const users: TestUser[] = [];
  let learner: Browser, other: Browser, session: SessionSnapshot;
  const startId = randomUUID();

  beforeAll(async () => {
    appOrigin();
    const first = await createVerifiedTestUser();
    users.push(first);
    const second = await createVerifiedTestUser();
    users.push(second);
    learner = await loginBrowser(first);
    other = await loginBrowser(second);
  }, 30_000);
  afterAll(async () => {
    await cleanupTestUsers(users);
  });

  it("serves setup-only guest previews and retires stateless answers", async () => {
    const catalogue = await api<ChallengePreviewListResponse>(
      null,
      "/api/challenges",
    );
    expect(catalogue.response.status).toBe(200);
    expect(catalogue.data.challenges).toHaveLength(3);
    for (const preview of catalogue.data.challenges) {
      const detail = await api<Record<string, unknown>>(
        null,
        `/api/challenges/${preview.id}`,
      );
      expect(detail.response.status).toBe(200);
      for (const field of [
        "question",
        "options",
        "decision",
        "reveal",
        "observedAction",
        "optionFeedback",
        "analysis",
      ]) {
        expect(preview).not.toHaveProperty(field);
        expect(detail.data).not.toHaveProperty(field);
      }
    }
    expect(
      (
        await api(
          null,
          `/api/challenges/${catalogue.data.challenges[0].id}/answer`,
          { optionId: "hold" },
        )
      ).response.status,
    ).toBe(401);
  });

  it("validates SSR identity and resumes one active session through actual Next services", async () => {
    const account = await api<AccountUser>(learner, "/api/account");
    expect(account.response.status).toBe(200);
    expect(account.data).toMatchObject({
      id: users[0].id,
      emailVerified: true,
      role: "learner",
      capabilities: ["learn"],
    });
    const first = await api<CreateSessionResponse>(learner, "/api/sessions", {
      requestId: startId,
    });
    expect(first.response.status).toBe(200);
    expect(first.data.created).toBe(true);
    session = first.data.session;
    expect(session.items).toHaveLength(3);
    expect(session.items.every((item) => item.answer === null)).toBe(true);
    const resume = await api<CreateSessionResponse>(learner, "/api/sessions", {
      requestId: randomUUID(),
    });
    expect(resume.data).toMatchObject({
      created: false,
      session: { id: session.id, revision: 0 },
    });
    expect(
      (
        await api(
          learner,
          `/api/challenges/${session.items[0].challenge.id}/answer`,
          { optionId: "hold" },
        )
      ).response.status,
    ).toBe(409);
  });

  it("persists answer/review, rejects stale or changed commands, and replays canonical progress", async () => {
    const command = savedCommand(session);
    const endpoint = `/api/sessions/${session.id}/items/${command.item.id}/answer`;
    const answer = await api<SessionMutationResponse>(
      learner,
      endpoint,
      command.body,
    );
    expect(answer.response.status).toBe(200);
    session = answer.data.session;
    expect(session).toMatchObject({ phase: "review", revision: 1 });
    expect(session.items[0].answer?.result.selectedOptionId).toBe(
      command.body.optionId,
    );
    expect(
      (await api<SessionSnapshot>(learner, `/api/sessions/${session.id}`)).data,
    ).toEqual(session);
    const altered = await api<{ error: { code: string } }>(learner, endpoint, {
      ...command.body,
      optionId: command.item.challenge.options[1].id,
    });
    expect(altered.response.status).toBe(409);
    expect(altered.data.error.code).toBe("IDEMPOTENCY_CONFLICT");
    const stale = await api<{ error: { code: string } }>(learner, endpoint, {
      ...command.body,
      requestId: randomUUID(),
    });
    expect(stale.response.status).toBe(409);
    expect(stale.data.error.code).toBe("SESSION_CONFLICT");
    const nextBody = {
      fromItemId: command.item.id,
      requestId: randomUUID(),
      expectedRevision: session.revision,
    };
    const advance = await api<SessionMutationResponse>(
      learner,
      `/api/sessions/${session.id}/advance`,
      nextBody,
    );
    expect(advance.response.status).toBe(200);
    session = advance.data.session;
    expect(session).toMatchObject({
      phase: "setup",
      currentIndex: 1,
      revision: 2,
    });
    const retry = await api<SessionMutationResponse>(
      learner,
      endpoint,
      command.body,
    );
    expect(retry.data).toMatchObject({
      replayed: true,
      session: { revision: 2, currentIndex: 1 },
    });
    const replayAdvance = await api<SessionMutationResponse>(
      learner,
      `/api/sessions/${session.id}/advance`,
      nextBody,
    );
    expect(replayAdvance.data).toMatchObject({
      replayed: true,
      session: { revision: 2, currentIndex: 1 },
    });
  });

  it("keeps final review until explicit Finish and preserves completed history", async () => {
    for (const index of [1, 2]) {
      const command = savedCommand(session);
      const answer = await api<SessionMutationResponse>(
        learner,
        `/api/sessions/${session.id}/items/${command.item.id}/answer`,
        command.body,
      );
      expect(answer.response.status).toBe(200);
      session = answer.data.session;
      expect(session).toMatchObject({
        phase: "review",
        currentIndex: index,
        completedAt: null,
      });
      expect(
        (await api<SessionSnapshot>(learner, `/api/sessions/${session.id}`))
          .data.phase,
      ).toBe("review");
      const next = await api<SessionMutationResponse>(
        learner,
        `/api/sessions/${session.id}/advance`,
        {
          fromItemId: command.item.id,
          requestId: randomUUID(),
          expectedRevision: session.revision,
        },
      );
      expect(next.response.status).toBe(200);
      session = next.data.session;
    }
    expect(session).toMatchObject({
      phase: "completed",
      currentIndex: null,
      revision: 6,
    });
    expect(session.completedAt).toBeTruthy();
    expect(session.items.every((item) => item.answer !== null)).toBe(true);
    const lateStart = await api<CreateSessionResponse>(
      learner,
      "/api/sessions",
      { requestId: startId },
    );
    expect(lateStart.data).toMatchObject({
      replayed: true,
      session: { id: session.id, phase: "completed" },
    });
    const another = await api<CreateSessionResponse>(learner, "/api/sessions", {
      requestId: randomUUID(),
    });
    expect(another.data.created).toBe(true);
    expect(another.data.session.id).not.toBe(session.id);
    expect(
      (await api<SessionSnapshot>(learner, `/api/sessions/${session.id}`)).data,
    ).toEqual(session);
  });

  it("returns indistinguishable foreign/missing ownership failures through Next routes", async () => {
    const foreign = await api(other, `/api/sessions/${session.id}`);
    const missing = await api(other, `/api/sessions/${randomUUID()}`);
    expect(foreign.response.status).toBe(404);
    expect(missing.response.status).toBe(404);
    expect(foreign.data).toEqual(missing.data);
    expect(
      (
        await api(other, `/api/sessions/${session.id}/advance`, {
          fromItemId: session.items[0].id,
          requestId: randomUUID(),
          expectedRevision: 6,
        })
      ).response.status,
    ).toBe(404);
  });

  it("rejects cross-origin and injected role writes; creator access does not expand ownership", async () => {
    expect(
      (
        await api(
          learner,
          "/api/sessions",
          { requestId: randomUUID() },
          { Origin: "https://evil.example" },
        )
      ).response.status,
    ).toBe(400);
    expect(
      (
        await api(
          learner,
          "/api/sessions",
          { requestId: randomUUID() },
          { "Content-Type": "text/plain" },
        )
      ).response.status,
    ).toBe(400);
    expect(
      (
        await api(other, "/api/account/creator", {
          userId: users[0].id,
          role: "creator",
        })
      ).response.status,
    ).toBe(400);
    const creator = await api<AccountUser>(other, "/api/account/creator", {});
    expect(creator.response.status).toBe(200);
    expect(creator.data).toMatchObject({
      id: users[1].id,
      role: "creator",
      capabilities: ["learn", "create"],
    });
    expect((await api(other, "/api/account/creator", {})).data).toEqual(
      creator.data,
    );
    expect(
      (await api(other, `/api/sessions/${session.id}`)).response.status,
    ).toBe(404);
    expect(
      (await api<SessionHistoryResponse>(other, "/api/sessions")).data.sessions,
    ).toEqual([]);
    expect(
      (
        await api<CreateSessionResponse>(other, "/api/sessions", {
          requestId: randomUUID(),
        })
      ).data.session.phase,
    ).toBe("setup");
  });

  it("restores saved data in a fresh cookie context and denies requests after local sign-out", async () => {
    const fresh = await loginBrowser(users[0]);
    expect(
      (await api<SessionSnapshot>(fresh, `/api/sessions/${session.id}`)).data,
    ).toEqual(session);
    const history = await api<SessionHistoryResponse>(fresh, "/api/sessions");
    expect(history.data.sessions).toHaveLength(2);
    expect(
      history.data.sessions.find((entry) => entry.id === session.id),
    ).toMatchObject({ status: "completed", answeredCount: 3, totalCount: 3 });
    await fresh.client.auth.signOut({ scope: "local" });
    expect((await api(fresh, "/api/account")).response.status).toBe(401);
  });
});
